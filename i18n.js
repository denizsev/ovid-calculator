const DEFAULT_LOCALE = "en";

function detectLocale() {
    const saved = storeGet("ovid-lang");
    if (saved && STRINGS[saved]) return saved;

    // first visit: follow the browser, but only into a locale we actually have
    for (const tag of (navigator.languages || [navigator.language || ""])) {
        const base = String(tag).toLowerCase().split("-")[0];
        if (STRINGS[base]) return base;
    }

    return DEFAULT_LOCALE;
}

let locale = detectLocale();

/* Missing keys fall back to English rather than to nothing, so a partly
   translated locale stays usable instead of showing blanks. */
function t(key, vars) {
    let text = STRINGS[locale]?.[key] ?? STRINGS[DEFAULT_LOCALE][key] ?? key;

    if (vars) {
        for (const name in vars) {
            text = text.split("{" + name + "}").join(vars[name]);
        }
    }

    return text;
}

const currentLocale = () => locale;

function applyTranslations(root = document) {
    root.querySelectorAll("[data-i18n]").forEach(el => {
        el.textContent = t(el.dataset.i18n);
    });

    root.querySelectorAll("[data-i18n-title]").forEach(el => {
        el.title = t(el.dataset.i18nTitle);
    });

    root.querySelectorAll("[data-i18n-aria-label]").forEach(el => {
        el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
    });

    root.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        el.placeholder = t(el.dataset.i18nPlaceholder);
    });

    document.documentElement.lang = locale;

    const desc = document.querySelector('meta[name="description"]');
    if (desc) desc.content = t(desc.dataset.i18n || "app.description");
}

/* Anything drawn by JS re-renders through this hook, so switching language
   never needs a reload. Each page registers what it owns. */
const localeListeners = [];
const onLocaleChange = fn => localeListeners.push(fn);

function setLocale(next) {
    if (!STRINGS[next]) return;

    locale = next;
    storeSet("ovid-lang", next);

    applyTranslations();
    localeListeners.forEach(fn => {
        try { fn(); } catch (e) { /* one bad listener must not stop the rest */ }
    });
}

function buildLanguagePicker(mountId) {
    const mount = document.getElementById(mountId);
    if (!mount) return;

    const select = document.createElement("select");
    select.id = "lang-select";
    select.className = "lang-select";
    select.title = t("chip.language");
    select.setAttribute("aria-label", t("chip.language"));

    for (const code in LOCALES) {
        const option = document.createElement("option");
        option.value = code;
        option.textContent = LOCALES[code].label;
        if (code === locale) option.selected = true;
        select.appendChild(option);
    }

    select.addEventListener("change", () => {
        setLocale(select.value);
        select.title = t("chip.language");
        select.setAttribute("aria-label", t("chip.language"));
        if (typeof showToast === "function") {
            showToast(t("toast.languageChanged", { l: LOCALES[locale].label }));
        }
    });

    mount.appendChild(select);
}

/* The markup ships in English; a saved or browser-detected locale has to be
   painted over it before anything else renders, otherwise a returning visitor
   sees English until they touch the picker. */
if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applyTranslations());
} else {
    applyTranslations();
}
